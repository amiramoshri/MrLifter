// Get exercise category color
export const getExerciseCategoryColor = (exerciseName: string): string => {
  const lowerName = exerciseName.toLowerCase();
  
  if (lowerName.includes('bench') || lowerName.includes('press') || lowerName.includes('push') || lowerName.includes('dips') || lowerName.includes('flyes')) {
    return 'from-red-600 to-red-700'; // Chest - Red
  }
  
  if (lowerName.includes('deadlift') || lowerName.includes('pull') || lowerName.includes('row') || lowerName.includes('lat')) {
    return 'from-blue-600 to-blue-700'; // Back - Blue
  }
  
  if (lowerName.includes('squat') || lowerName.includes('leg') || lowerName.includes('lunge') || lowerName.includes('calf')) {
    return 'from-green-600 to-green-700'; // Legs - Green
  }
  
  if (lowerName.includes('overhead') || lowerName.includes('lateral') || lowerName.includes('shoulder') || lowerName.includes('shrug')) {
    return 'from-yellow-600 to-yellow-700'; // Shoulders - Yellow
  }
  
  if (lowerName.includes('curl') || lowerName.includes('tricep') || lowerName.includes('arm')) {
    return 'from-purple-600 to-purple-700'; // Arms - Purple
  }
  
  if (lowerName.includes('burpee') || lowerName.includes('mountain') || lowerName.includes('battle') || lowerName.includes('kettlebell') || lowerName.includes('plank')) {
    return 'from-orange-600 to-orange-700'; // Functional - Orange
  }
  
  if (lowerName.includes('run') || lowerName.includes('jog') || lowerName.includes('cycle') || lowerName.includes('swim') || lowerName.includes('sprint')) {
    return 'from-cyan-600 to-cyan-700'; // Cardio - Cyan
  }
  
  return 'from-gray-600 to-gray-700'; // Default - Gray
};